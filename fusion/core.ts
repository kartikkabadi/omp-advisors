/**
 * Bounded, dependency-free fusion orchestration.
 *
 * Pure logic: no filesystem, subprocess, SDK, or UI access. Runs 2..8
 * candidates strictly sequentially, scores each through an injected judge,
 * tracks the best answer, retains every piece of evidence and dissent, and
 * stops on the first of:
 *
 *   - quality threshold reached after the minimum candidate count,
 *   - marginal gain (improvement over the incumbent best) at or below the
 *     marginal-gain threshold,
 *   - candidate budget exhausted,
 *   - abort signalled through the shared AbortSignal.
 *
 * Deterministic by construction: candidates execute one await at a time in
 * run order, so stopping is a pure function of the observed scores and
 * never depends on scheduling.
 */

/** Why the fusion run stopped. */
export type FusionStopReason = "threshold" | "marginal-gain" | "budget" | "aborted";

/** One candidate answer. */
export interface FusionCandidate {
  /** Stable identifier, generated by the runner as `candidate-<index>`. */
  id: string;
  /** The candidate's answer text. */
  output: string;
}

/** A supporting observation about one candidate, retained from the judge. */
export interface FusionEvidence {
  candidateId: string;
  note: string;
}

/** A dissenting observation about one candidate, retained from the judge. */
export interface FusionDissent {
  candidateId: string;
  note: string;
}

/** A candidate that failed to run or to be judged. */
export interface FusionFailure {
  candidateId: string;
  phase: "run" | "judge";
  error: string;
}

/** A judge's verdict on one candidate. */
export interface FusionJudgement {
  /** 0..1 quality score for the candidate. */
  score: number;
  /** Supporting observations, retained verbatim. */
  evidence?: string[];
  /** Dissenting observations, retained verbatim. */
  dissent?: string[];
}

/** Lifecycle phase of a single progress event. */
export type FusionProgressPhase = "started" | "completed" | "failed" | "done";

/**
 * A single progress event. Delivered to `onProgress` as it happens and
 * retained in `result.progress` for later reporting.
 */
export interface FusionProgress {
  /**
   * Zero-based candidate index for `started`/`completed`/`failed` events;
   * for the terminal `done` event, the number of candidate attempts.
   */
  candidateIndex: number;
  candidateId: string | null;
  phase: FusionProgressPhase;
  /** Set on `completed`; null otherwise. */
  score: number | null;
  /** Running best score at the moment the event was emitted. */
  bestScore: number | null;
  /** Set on `failed`. */
  error: string | null;
  /** Set on the event that caused the stop, and on `done`. */
  stopReason: FusionStopReason | null;
}

export interface FusionOptions {
  /** Candidates to run before adaptive stopping is allowed. Default 2; clamped to [MIN_CANDIDATES, maxCandidates]. */
  minCandidates?: number;
  /** Candidate budget. Default 4; clamped to [2, 8]. */
  maxCandidates?: number;
  /** Stop when the running best is at or above this (0..1). Default 0.9. */
  qualityThreshold?: number;
  /** Stop when the newest candidate improves the incumbent best by at most this. Default 0.02. */
  marginalGainThreshold?: number;
  /** Shared abort signal, checked before each candidate run and before each judge. */
  signal?: AbortSignal;
  /** Invoked for every progress event, including the terminal `done` event. */
  onProgress?: (progress: FusionProgress) => void;
}

export interface FusionDependencies {
  /** Execute one candidate; resolves to its answer text. May reject. */
  runCandidate: (prompt: string, candidateId: string, signal?: AbortSignal) => Promise<string>;
  /**
   * Score one candidate; resolves to a verdict. May reject, or return a
   * non-finite score, which is treated as a judge failure: the candidate is
   * retained but unjudged, and any evidence/dissent on the invalid verdict
   * are discarded with it.
   */
  judge: (prompt: string, candidate: FusionCandidate, signal?: AbortSignal) => Promise<FusionJudgement>;
}

export interface FusionResult {
  stopReason: FusionStopReason;
  /** The highest-scoring judged candidate, or null when none was judged. */
  best: FusionCandidate | null;
  bestScore: number | null;
  /** Candidates that produced output, in run order. Unscored candidates (judge failure or abort) are present. */
  candidates: FusionCandidate[];
  /** candidateId -> 0..1 score, for judged candidates only. */
  scores: Record<string, number>;
  /** All supporting observations, retained in judge order. */
  evidence: FusionEvidence[];
  /** All dissenting observations, retained in judge order. */
  dissent: FusionDissent[];
  failures: FusionFailure[];
  /** Number of candidate attempts consumed against the budget. */
  candidatesRun: number;
  progress: FusionProgress[];
}

/** Hard lower bound on the candidate budget. */
export const MIN_CANDIDATES = 2;
/** Hard upper bound on the candidate budget. */
export const MAX_CANDIDATES = 8;
/** Default candidate budget when `maxCandidates` is omitted. */
export const DEFAULT_MAX_CANDIDATES = 4;

const DEFAULT_MIN_CANDIDATES = MIN_CANDIDATES;
const DEFAULT_QUALITY_THRESHOLD = 0.9;
const DEFAULT_MARGINAL_GAIN_THRESHOLD = 0.02;

interface NormalizedOptions {
  minCandidates: number;
  maxCandidates: number;
  qualityThreshold: number;
  marginalGainThreshold: number;
  signal: AbortSignal | undefined;
  onProgress: ((progress: FusionProgress) => void) | undefined;
}

function clamp(value: number, min: number, max: number): number {
  return Math.min(max, Math.max(min, value));
}

function errorMessage(err: unknown): string {
  return err instanceof Error ? err.message : String(err);
}

function normalizeOptions(options: FusionOptions): NormalizedOptions {
  const maxCandidates = clamp(
    Math.trunc(options.maxCandidates ?? DEFAULT_MAX_CANDIDATES),
    MIN_CANDIDATES,
    MAX_CANDIDATES,
  );
  const minCandidates = clamp(Math.trunc(options.minCandidates ?? DEFAULT_MIN_CANDIDATES), MIN_CANDIDATES, maxCandidates);
  const qualityThreshold = clamp(options.qualityThreshold ?? DEFAULT_QUALITY_THRESHOLD, 0, 1);
  const marginalGainThreshold = clamp(options.marginalGainThreshold ?? DEFAULT_MARGINAL_GAIN_THRESHOLD, 0, 1);
  return {
    minCandidates,
    maxCandidates,
    qualityThreshold,
    marginalGainThreshold,
    signal: options.signal,
    onProgress: options.onProgress,
  };
}

/**
 * Run a bounded fusion over the prompt.
 *
 * Orchestration: for each of up to `maxCandidates` budget slots, run one
 * candidate through `dependencies.runCandidate`, then score it through
 * `dependencies.judge`. The shared `options.signal` is checked before each
 * run and before each judge; an aborted signal stops the run and preserves
 * whatever best, evidence, and dissent were already collected. A run or
 * judge that rejects after the signal has aborted is treated as cancellation,
 * not a candidate failure, and stops the run as `aborted` without recording
 * a failure. Candidate and judge failures that are not cancellation are
 * captured in `result.failures` and never abort the run.
 *
 * Stopping (in priority order, after `minCandidates` attempts):
 *   1. `threshold`      - the running best is at or above `qualityThreshold`.
 *   2. `marginal-gain`  - the newest candidate improved the incumbent best
 *                         by at most `marginalGainThreshold`.
 *   3. `budget`         - all `maxCandidates` slots were consumed.
 *   4. `aborted`        - the shared signal fired first.
 *
 * The terminal stop reason is always reported via `result.stopReason` and
 * the final `done` progress event.
 */
export async function runFusion(
  prompt: string,
  options: FusionOptions,
  dependencies: FusionDependencies,
): Promise<FusionResult> {
  const opts = normalizeOptions(options);
  const { runCandidate, judge } = dependencies;

  const candidates: FusionCandidate[] = [];
  const scores: Record<string, number> = {};
  const evidence: FusionEvidence[] = [];
  const dissent: FusionDissent[] = [];
  const failures: FusionFailure[] = [];
  const progress: FusionProgress[] = [];

  let best: FusionCandidate | null = null;
  let bestScore: number | null = null;
  let stopReason: FusionStopReason | null = null;
  let candidatesRun = 0;

  const emit = (event: FusionProgress): void => {
    progress.push(event);
    opts.onProgress?.(event);
  };

  for (let i = 0; i < opts.maxCandidates; i++) {
    if (opts.signal?.aborted) {
      stopReason = "aborted";
      break;
    }

    const candidateId = `candidate-${i}`;
    candidatesRun = i + 1;

    emit({
      candidateIndex: i,
      candidateId,
      phase: "started",
      score: null,
      bestScore,
      error: null,
      stopReason: null,
    });

    let output: string;
    try {
      output = await runCandidate(prompt, candidateId, opts.signal);
    } catch (err) {
      if (opts.signal?.aborted) {
        // The runner rejected because the shared signal aborted: this is
        // cancellation, not a candidate failure.
        stopReason = "aborted";
        break;
      }
      const error = errorMessage(err);
      failures.push({ candidateId, phase: "run", error });
      emit({ candidateIndex: i, candidateId, phase: "failed", score: null, bestScore, error, stopReason: null });
      continue;
    }

    const candidate: FusionCandidate = { id: candidateId, output };
    candidates.push(candidate);

    if (opts.signal?.aborted) {
      stopReason = "aborted";
      break;
    }

    let judgement: FusionJudgement;
    try {
      judgement = await judge(prompt, candidate, opts.signal);
    } catch (err) {
      if (opts.signal?.aborted) {
        // The judge rejected because the shared signal aborted: this is
        // cancellation, not a candidate failure.
        stopReason = "aborted";
        break;
      }
      const error = errorMessage(err);
      failures.push({ candidateId, phase: "judge", error });
      emit({ candidateIndex: i, candidateId, phase: "failed", score: null, bestScore, error, stopReason: null });
      continue;
    }

    // An invalid (non-finite) verdict is a judge failure: the candidate is
    // retained but unjudged, and any evidence/dissent the judge attached to
    // the verdict are discarded with it.
    if (!Number.isFinite(judgement.score)) {
      const error = `judge returned non-finite score: ${String(judgement.score)}`;
      failures.push({ candidateId, phase: "judge", error });
      emit({ candidateIndex: i, candidateId, phase: "failed", score: null, bestScore, error, stopReason: null });
      continue;
    }

    const score = clamp(judgement.score, 0, 1);
    scores[candidateId] = score;

    for (const note of judgement.evidence ?? []) {
      evidence.push({ candidateId, note });
    }
    for (const note of judgement.dissent ?? []) {
      dissent.push({ candidateId, note });
    }

    const previousBest = bestScore;
    if (bestScore === null || score > bestScore) {
      best = candidate;
      bestScore = score;
    }

    const completed = i + 1;
    if (completed >= opts.minCandidates) {
      if (bestScore >= opts.qualityThreshold) {
        stopReason = "threshold";
      } else if (previousBest !== null && bestScore - previousBest <= opts.marginalGainThreshold) {
        stopReason = "marginal-gain";
      }
    }

    emit({
      candidateIndex: i,
      candidateId,
      phase: "completed",
      score,
      bestScore,
      error: null,
      stopReason,
    });

    if (stopReason !== null) {
      break;
    }
  }

  if (stopReason === null) {
    stopReason = "budget";
  }

  emit({
    candidateIndex: candidatesRun,
    candidateId: null,
    phase: "done",
    score: null,
    bestScore,
    error: null,
    stopReason,
  });

  return {
    stopReason,
    best,
    bestScore,
    candidates,
    scores,
    evidence,
    dissent,
    failures,
    candidatesRun,
    progress,
  };
}
